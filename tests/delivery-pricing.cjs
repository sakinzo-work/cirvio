const assert = require('node:assert/strict');
const { calculateDelivery, applyCourierQuote } = require('../cirvio-backend/services/delivery-pricing');
function quote(input) { return calculateDelivery({ subtotal: 350, shipmentWeightKg: 0.5, deliveryCity: 'Panvel', originCities: ['Panvel'], distanceKm: 6.4, ...input }); }
const local = quote({});
assert.equal(local.type, 'local'); assert.equal(local.baseFee, 89); assert.equal(local.finalFee, 89);
assert.equal(quote({ distanceKm: 2 }).finalFee, 49);
assert.equal(quote({ distanceKm: 5 }).finalFee, 69);
assert.equal(quote({ distanceKm: 8 }).finalFee, 89);
assert.equal(quote({ distanceKm: 12 }).finalFee, 119);
assert.equal(quote({ distanceKm: 15 }).finalFee, 149);
assert.equal(quote({ distanceKm: 16 }).finalFee, 159);
const midCourier = calculateDelivery({ subtotal: 750, shipmentWeightKg: 1.3, deliveryCity: 'Pune', originCities: ['Panvel'] });
assert.equal(midCourier.type, 'courier'); assert.equal(midCourier.baseFee, 139); assert.equal(midCourier.deliveryDiscount, 30); assert.equal(midCourier.finalFee, 109);
const freeCourier = calculateDelivery({ subtotal: 1200, shipmentWeightKg: 1.5, deliveryCity: 'Pune', originCities: ['Panvel'] });
assert.equal(freeCourier.baseFee, 139); assert.equal(freeCourier.deliveryDiscount, 139); assert.equal(freeCourier.finalFee, 0);
const heavy = calculateDelivery({ subtotal: 1200, shipmentWeightKg: 5.1, deliveryCity: 'Pune', originCities: ['Panvel'] });
assert.equal(heavy.quoteStatus, 'needs-courier-quote');
const confirmed = applyCourierQuote(heavy, 1200, 240);
assert.equal(confirmed.handlingFee, 30); assert.equal(confirmed.finalFee, 270, 'Heavy shipments do not get automatic free delivery');
console.log('PASS Delivery pricing slabs, discounts and heavy courier quote handling');
